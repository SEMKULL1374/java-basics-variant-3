// Импортируем класс Scanner для считывания ввода пользователя с клавиатуры
import java.util.Scanner;

public class Main {
    // Точка входа в программу: выполнение начинается отсюда
    public static void main(String[] args) {
        // Создаём объект Scanner, который читает данные из стандартного потока ввода (клавиатура)
        Scanner scanner = new Scanner(System.in);
         // Объявляем массив на 5 элементов для хранения сумм покупок
        int[] purchases = new int[5];
 // Выводим приглашение для пользователя: просим ввести 5 сумм
        System.out.println("Введите 5 сумм покупок (в рублях):");
        // Запускаем цикл ровно на 5 итераций — по одной для каждой покупки
        for (int i = 0; i < purchases.length; i++) {
            // Подсказываем пользователю, какую по счёту покупку он вводит
            System.out.print("Покупка №" + (i + 1) + ": ");
            // Считываем целое число, введённое пользователем, и сохраняем в ячейку массива
            purchases[i] = scanner.nextInt();
        }
        // Закрываем сканер, чтобы освободить системные ресурсы и избежать утечек
        scanner.close();
// Объявляем переменную для хранения общей суммы покупок, изначально она равна 0
        int totalSum = 0;
        // Проходим по всем элементам массива покупок и суммируем их
        for (int purchase : purchases) {
            totalSum += purchase;// Добавляем текущую покупку к общей сумме
        }
// Объявляем переменную для процента кэшбека (используем double для дробных значений)
        double bonusPercent;
        // Проверяем условия программы лояльности по убыванию суммы
        if (totalSum > 5000) {
             // Если общая сумма больше 5000 рублей — начисляем 10% кэшбека
            bonusPercent = 10.0;
            // Если сумма больше 2000, но не превышает 5000 — начисляем 5% кэшбека
        } else if (totalSum > 2000) {
            bonusPercent = 5.0;
            // Во всех остальных случаях (сумма 2000 и меньше) кэшбек равен 0%
        } else {
            bonusPercent = 0.0;
        }
// Рассчитываем итоговую сумму бонусов: общая сумма * процент / 100
        double bonusAmount = totalSum * (bonusPercent / 100.0);
 // Печатаем общую сумму покупок
        System.out.println("\nОбщая сумма покупок: " + totalSum + " руб.");
        // Печатаем процент кэшбека, который применился по условиям
        System.out.println("Процент кэшбека: " + bonusPercent + "%");
         // Печатаем итоговую сумму начисленных бонусов
        System.out.println("Начислено бонусов: " + bonusAmount + " руб.");
    }
}
